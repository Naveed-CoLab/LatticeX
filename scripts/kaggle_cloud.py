"""Run every heavy LatticeIQ job on Kaggle. Your PC only sends commands and receives results.

One-time setup
  python -m scripts.kaggle_cloud upload-secrets     API keys -> private Kaggle dataset (only your account can read it)
  python -m scripts.kaggle_cloud upload-data        prices + macro (+ news/fundamentals if present) -> private dataset

News (Benzinga + FinBERT)
  python -m scripts.kaggle_cloud news-probe                    how many years of news your plan has (prints the answer)
  python -m scripts.kaggle_cloud news-probe --diagnose 2019-03 single vs batched requests, total news per day
  python -m scripts.kaggle_cloud news-download --start 2015-01 download history on Kaggle (CPU, no GPU hours used)
      (very long history? do it in chunks under 12 h each: --start 2015-01 --end 2019-12, then --start 2020-01)
  python -m scripts.kaggle_cloud news-score                    FinBERT on Kaggle's GPU

Fundamentals (SEC EDGAR, CPU, ~10-20 min)
  python -m scripts.kaggle_cloud fundamentals-download

Kronos (pretrained, zero-shot, GPU)
  python -m scripts.kaggle_cloud kronos --timing              speed test (~5-10 min), estimates the full run
  python -m scripts.kaggle_cloud kronos --years 2010 2016     one chunk (then --years 2017 2024)

TimesFM 2.5 (pretrained, zero-shot, GPU, weekly forecasts)
  python -m scripts.kaggle_cloud timesfm --timing             speed test (~5 min), estimates the full run
  python -m scripts.kaggle_cloud timesfm --years 2010 2024    full run

Experiments (GPU)
  python -m scripts.kaggle_cloud experiments "--data real --no-macro" "--data real" "--data real --news"

Price brackets (GPU)
  python -m scripts.kaggle_cloud brackets "--data real" "--data real --horizon 5" "--data real --horizon 60"

Every command waits for Kaggle to finish, then copies the outputs to your PC:
  data files -> data\\clean\\        results -> results\\        logs -> results\\kaggle_<job>.log
Add --no-wait to start a job and return immediately; collect later with:
  python -m scripts.kaggle_cloud download <job>      jobs: news-probe, news-download, news-score, experiments
  (news chunks run as separate jobs named by start year and can run at the same time;
   collect one with: download news-download --start 2015-01)
  python -m scripts.kaggle_cloud status <job>

Kaggle limits: 12 h per run, ~30 GPU h/week. Download jobs run on CPU and don't use GPU hours.
"""
import base64
import io
import json
import shutil
import sys
import time
import zipfile

import pandas as pd

from scripts.kaggle_news import kaggle, kaggle_user
from src.config import ROOT, path

DATA_SLUG, SECRETS_SLUG = "latticeiq-data", "latticeiq-secrets"
DATA_FILES = ["prices.parquet", "macro.parquet", "news_articles.parquet", "news_scored.parquet",
              "fundamentals.parquet", "kronos_forecasts.parquet", "timesfm_forecasts.parquet"]
SECRET_KEYS = ["BENZINGA_API_KEY", "FRED_API_KEY", "TIINGO_API_KEY", "SEC_USER_AGENT"]
CODE_DIRS = ["src", "scripts", "config"]

# name -> kernel settings. "sources" are earlier jobs whose outputs this job reads.
JOBS = {
    "news-probe":    {"gpu": False, "secrets": True, "sources": [], "keep": []},
    "news-download": {"gpu": False, "secrets": True, "sources": [], "keep": ["data/clean/news_articles.parquet"]},
    "fundamentals-download": {"gpu": False, "secrets": True, "sources": [],
                              "keep": ["data/clean/fundamentals.parquet"]},
    "news-score":    {"gpu": True, "secrets": False, "sources": [], "keep": ["data/clean/news_scored.parquet"]},
    "experiments":   {"gpu": True, "secrets": False, "sources": [], "keep": ["results"]},
    "brackets":      {"gpu": True, "secrets": False, "sources": [], "keep": ["results"]},
    "kronos":        {"gpu": True, "secrets": False, "sources": [],
                      "keep": ["data/clean/kronos_forecasts.parquet", "data/clean/kronos_timing.parquet"]},
    "timesfm":       {"gpu": True, "secrets": False, "sources": [],
                      "keep": ["data/clean/timesfm_forecasts.parquet", "data/clean/timesfm_timing.parquet"]},
}

TEMPLATE = r'''# LatticeIQ cloud job "__NAME__". Generated by scripts/kaggle_cloud.py; edit the code on your PC, not here.
import base64, glob, io, os, shutil, subprocess, sys, time, zipfile
CODE, STEPS, KEEP, DATA_FILES = "__CODE__", __STEPS__, __KEEP__, __DATA_FILES__
SECRET_KEYS = __SECRETS__
INPUT = os.getenv("LIQ_INPUT", "/kaggle/input")
WORK = os.getenv("LIQ_WORKING", "/kaggle/working")
root = os.path.join(WORK, "lattice")
zipfile.ZipFile(io.BytesIO(base64.b64decode(CODE))).extractall(root)
clean = os.path.join(root, "data", "clean")
os.makedirs(clean, exist_ok=True)
for name in DATA_FILES:                       # newest copy of each known data file from the inputs
    found = sorted(glob.glob(os.path.join(INPUT, "**", name), recursive=True), key=os.path.getmtime)
    if found:
        shutil.copy(found[-1], os.path.join(clean, name))
print("data:", sorted(os.listdir(clean)), flush=True)

env = dict(os.environ)
loaded = []
for f in glob.glob(os.path.join(INPUT, "**", "latticeiq.env"), recursive=True):
    for line in open(f, encoding="utf-8"):
        if "=" in line and not line.strip().startswith("#"):
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip().strip('"')
            loaded.append(k.strip())
try:                                           # Kaggle Secrets (Add-ons > Secrets) also work
    from kaggle_secrets import UserSecretsClient
    c = UserSecretsClient()
    for k in SECRET_KEYS:
        if k not in env:
            try:
                env[k] = c.get_secret(k); loaded.append(k)
            except Exception:
                pass
except Exception:
    pass
if SECRET_KEYS:
    print("secrets loaded:", sorted(set(loaded) & set(SECRET_KEYS)) or "NONE (run upload-secrets on your PC)", flush=True)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "python-dotenv", "tenacity"], check=False)
try:
    import torch
    gpu = torch.cuda.is_available()
except Exception:
    gpu = False
env["LATTICEIQ_DEVICE"] = "cuda" if gpu else "cpu"
print("device:", env["LATTICEIQ_DEVICE"], flush=True)

logdir = os.path.join(WORK, "out", "logs")
os.makedirs(logdir, exist_ok=True)
for i, step in enumerate(STEPS, 1):
    print(f"\n===== step {i}/{len(STEPS)}: python -m {step} =====", flush=True)
    t0 = time.time()
    with open(os.path.join(logdir, f"step{i:02d}.log"), "w") as log:
        log.write(f"$ python -m {step}\n\n")
        p = subprocess.Popen([sys.executable, "-u", "-m", *step.split()], cwd=root, env=env,
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        for line in p.stdout:
            print(line, end="", flush=True)
            log.write(line)
        p.wait()
        log.write(f"\n(exit {p.returncode}, {time.time() - t0:.0f}s)\n")
    if p.returncode != 0:
        print(f"step {i} failed (exit {p.returncode}); stopping", flush=True)
        break
for k in KEEP:
    src = os.path.join(root, k)
    dst = os.path.join(WORK, "out", k)
    if os.path.isdir(src):
        shutil.copytree(src, dst, dirs_exist_ok=True)
    elif os.path.exists(src):
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy(src, dst)
shutil.rmtree(root, ignore_errors=True)        # notebook output = out/ only
print("done", flush=True)
'''


def _code_b64() -> str:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for d in CODE_DIRS:
            for f in (ROOT / d).rglob("*"):
                if f.is_file() and "__pycache__" not in f.parts and f.suffix != ".pyc":
                    z.write(f, f.relative_to(ROOT).as_posix())
    return base64.b64encode(buf.getvalue()).decode()


def build_script(name: str, steps: list) -> str:
    j = JOBS[name]
    return (TEMPLATE.replace("__NAME__", name).replace("__CODE__", _code_b64())
            .replace("__STEPS__", json.dumps(steps)).replace("__KEEP__", json.dumps(j["keep"]))
            .replace("__DATA_FILES__", json.dumps(DATA_FILES))
            .replace("__SECRETS__", json.dumps(SECRET_KEYS if j["secrets"] else [])))


def slug(name: str, variant: str = "") -> str:
    return f"latticeiq-{name}" + (f"-{variant}" if variant else "")


def variant_of(name: str, args: list) -> str:
    """Chunked jobs run as separate Kaggle jobs: news by start year, Kronos by --years FROM or 'timing'."""
    if name == "news-download" and "--start" in args:
        return args[args.index("--start") + 1][:4]
    if name in ("kronos", "timesfm"):
        if "--timing" in args:
            return "timing"
        if "--years" in args:
            return args[args.index("--years") + 1]
    return ""


def _upload_dataset(dataset_slug: str, files: dict) -> None:
    user = kaggle_user()
    folder = ROOT / "data" / "kaggle_upload" / dataset_slug
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    for name, content_or_path in files.items():
        if isinstance(content_or_path, str):
            (folder / name).write_text(content_or_path, encoding="utf-8")
        else:
            shutil.copy2(content_or_path, folder / name)
    (folder / "dataset-metadata.json").write_text(json.dumps(
        {"title": dataset_slug, "id": f"{user}/{dataset_slug}", "licenses": [{"name": "other"}]}, indent=2))
    r = kaggle("datasets", "version", "-p", str(folder), "-m", "update", "-t", "-d", check=False)
    if r.returncode != 0 or "not found" in (r.stdout + r.stderr).lower():
        kaggle("datasets", "create", "-p", str(folder), "-t")
    if dataset_slug == SECRETS_SLUG:
        shutil.rmtree(folder, ignore_errors=True)   # don't leave a copy of the keys lying around


def upload_secrets() -> None:
    env_file = ROOT / ".env"
    if not env_file.exists():
        raise SystemExit(".env not found in the project folder.")
    keep = [l for l in env_file.read_text(encoding="utf-8").splitlines()
            if l.split("=", 1)[0].strip() in SECRET_KEYS and "=" in l and l.split("=", 1)[1].strip()]
    print("Uploading keys:", [l.split("=", 1)[0].strip() for l in keep], f"-> private dataset {SECRETS_SLUG}")
    _upload_dataset(SECRETS_SLUG, {"latticeiq.env": "\n".join(keep) + "\n"})
    print("Done. Only your Kaggle account can read it. Re-run this after you rotate a key.")


def upload_data() -> None:
    empty = [n for n in DATA_FILES if (path("clean") / n).exists() and (path("clean") / n).stat().st_size == 0]
    if empty:
        raise SystemExit(f"Refusing to upload: these files are EMPTY (0 bytes): {empty}. Restore them first "
                         f"(e.g. copy from data\\kaggle_out\\...\\out\\data\\clean\\), then run upload-data again.")
    files = {n: path("clean") / n for n in DATA_FILES if (path("clean") / n).exists()}
    if not files:
        raise SystemExit("data/clean is empty.")
    for n, f in files.items():
        print(f"  + {n} ({f.stat().st_size / 1e6:.0f} MB)")
    _upload_dataset(DATA_SLUG, files)
    print("Uploaded. Give Kaggle a few minutes to process it before starting a job.")


def push(name: str, steps: list, variant: str = "") -> None:
    user, j = kaggle_user(), JOBS[name]
    folder = ROOT / "data" / "kaggle_upload" / f"kernel_{slug(name, variant)}"
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    (folder / "job.py").write_text(build_script(name, steps), encoding="utf-8")
    datasets = [f"{user}/{DATA_SLUG}"] + ([f"{user}/{SECRETS_SLUG}"] if j["secrets"] else [])
    (folder / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{user}/{slug(name, variant)}", "title": slug(name, variant), "code_file": "job.py",
        "language": "python", "kernel_type": "script", "is_private": True,
        "enable_gpu": j["gpu"], "enable_internet": True, "dataset_sources": datasets,
        "kernel_sources": [f"{user}/{slug(s)}" for s in j["sources"]], "competition_sources": [],
    }, indent=2))
    args = ["kernels", "push", "-p", str(folder)] + (["--accelerator", "NvidiaTeslaT4"] if j["gpu"] else [])
    r = kaggle(*args)
    out = (r.stdout + r.stderr).lower()
    if "error" in out or "successfully pushed" not in out:
        raise SystemExit("Push to Kaggle failed (nothing started). Wait 2-3 minutes and run the same command again.")
    print(f"Started '{name}' on Kaggle ({'GPU' if j['gpu'] else 'CPU'}). "
          f"Watch: https://www.kaggle.com/code/{user}/{slug(name, variant)}")


def status(name: str, variant: str = "") -> str:
    r = kaggle("kernels", "status", f"{kaggle_user()}/{slug(name, variant)}", check=False)
    t = (r.stdout + r.stderr).lower()
    return next((s for s in ("complete", "error", "cancel", "running", "queued") if s in t), "unknown")


def download(name: str, wait: bool = True, poll_minutes: int = 2, variant: str = "") -> None:
    while wait:
        s = status(name, variant)
        print(f"{time.strftime('%H:%M')} {slug(name, variant)}: {s}")
        if s in ("complete", "error", "cancel"):
            break
        time.sleep(poll_minutes * 60)
    out = ROOT / "data" / "kaggle_out" / slug(name, variant)
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    kaggle("kernels", "output", f"{kaggle_user()}/{slug(name, variant)}", "-p", str(out), "-o")
    base = out / "out" if (out / "out").exists() else out
    got_data = False
    for f in (base / "data" / "clean").glob("*.parquet") if (base / "data" / "clean").exists() else []:
        dest = path("clean") / f.name
        keys = {"news_articles.parquet": ["id"], "news_scored.parquet": ["id"],
                "kronos_forecasts.parquet": ["date", "ticker"], "timesfm_forecasts.parquet": ["date", "ticker"]}.get(f.name)
        if keys and dest.exists() and dest.stat().st_size > 0:
            # chunked outputs (news months, Kronos years): merge, never overwrite
            merged = pd.concat([pd.read_parquet(dest), pd.read_parquet(f)]).drop_duplicates(keys, keep="last")
            merged.to_parquet(dest, index=False)
            print(f"  -> data\\clean\\{f.name}: merged, now {len(merged):,} rows")
        else:
            shutil.copy2(f, dest)
            print(f"  -> data\\clean\\{f.name} ({f.stat().st_size / 1e6:.0f} MB)")
        got_data = True
    if (base / "results").exists():
        for item in (base / "results").iterdir():
            if item.is_dir():
                shutil.copytree(item, path("results") / item.name, dirs_exist_ok=True)
                for mname in ("metrics.csv", "bracket_metrics.csv"):
                    m = item / mname
                    if m.exists():
                        print(f"\n{item.name}\n{pd.read_csv(m).round(4).to_string(index=False)}")
    for log in sorted((base / "logs").glob("*.log")) if (base / "logs").exists() else []:
        dest = path("results") / f"kaggle_{slug(name, variant)}_{log.name}"
        shutil.copy2(log, dest)
        if name == "news-probe" or log.stat().st_size < 4000:
            print(log.read_text(encoding="utf-8", errors="replace")[-3000:])
    print(f"\nLogs saved as results\\kaggle_{name}_step*.log")
    if got_data:
        print("\nRe-uploading data so the next Kaggle job sees it...")
        upload_data()


def main(argv: list) -> None:
    if not argv:
        return print(__doc__)
    cmd, rest = argv[0], argv[1:]
    wait = "--no-wait" not in rest
    rest = [a for a in rest if a != "--no-wait"]
    if cmd == "upload-secrets":
        return upload_secrets()
    if cmd == "upload-data":
        return upload_data()
    if cmd in ("status", "download"):
        if not rest or rest[0] not in JOBS:
            raise SystemExit(f"which job? one of: {', '.join(JOBS)}  (news chunks: download news-download --start 2015-01)")
        v = variant_of(rest[0], rest[1:])
        return print(status(rest[0], v)) if cmd == "status" else download(rest[0], variant=v)
    if cmd == "news-probe":
        steps = ["src.ingest.benzinga " + (" ".join(rest) if rest else "--probe")]
    elif cmd == "news-download":
        if "--start" not in rest:
            raise SystemExit("give a start month, e.g. news-download --start 2015-01 (see news-probe)")
        steps = ["src.ingest.benzinga " + " ".join(rest)]
    elif cmd == "fundamentals-download":
        steps = ["src.ingest.edgar " + " ".join(rest)]
    elif cmd == "news-score":
        steps = ["src.news.sentiment"]
    elif cmd == "experiments":
        jobs = rest or ["--data real"]
        for j in jobs:
            if "--data" not in j:
                raise SystemExit(f'each experiment needs --data, e.g. "--data real". Got: {j!r}')
        steps = ["scripts.run_experiment " + j for j in jobs]
    elif cmd == "kronos":
        steps = ["src.models.kronos_runner " + " ".join(rest)]
    elif cmd == "timesfm":
        steps = ["src.models.timesfm_runner " + " ".join(rest)]
    elif cmd == "brackets":
        jobs = rest or ["--data real"]
        steps = ["scripts.run_brackets " + j for j in jobs]
    else:
        raise SystemExit(f"unknown command {cmd!r}\n{__doc__}")
    v = variant_of(cmd, rest)
    push(cmd, steps, v)
    if wait:
        time.sleep(45)
        download(cmd, variant=v)


if __name__ == "__main__":
    main(sys.argv[1:])
